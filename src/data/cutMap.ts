/** Normalized lookup: lowercased trimmed product name -> { animalId, cutId, productName } */
export const PRODUCT_TO_CUT_LOOKUP: Record<string, { animalId: AnimalId; cutId: string; productName: string }> = {};

// Build reverse lookup index
for (const animal of Object.values(CUT_MAP_DATA)) {
    for (const cut of animal.cuts) {
        for (const prod of cut.products) {
            const key = prod.trim().toLowerCase();
            PRODUCT_TO_CUT_LOOKUP[key] = {
                animalId: animal.id,
                cutId: cut.id,
                productName: prod,
            };
        }
    }
}

