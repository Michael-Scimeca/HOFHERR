function buildExtendedSheet(seed: ExtendedSheetSeed): ResolvedCookingSheet {
    const bedBox = BED_COORDS[seed.bedShape];
    const primaryBox = PRIMARY_COORDS[seed.primaryShape];
    const onlineOrderPath = `/online-orders?q=${encodeURIComponent(seed.buyName)}`;
    const onlineOrderQrUrl = 'https://hofherrmeatco.com/';

    const primaryBuy: BuyPlan = {
        item: {
            name: seed.buyName,
            price: seed.buyPrice,
            unitPrice: seed.buyUnitPrice,
            unit: 'lb',
            baseAmount: 1,
            pieceLb: 0.5,
            pieceLabel: 'cut',
        },
        qty: 2,
        lb: 1,
        label: seed.buyLabel,
        cost: seed.buyUnitPrice,
    };

    const syntheticRecipe: Recipe = {
        slug: seed.recipeSlug ?? seed.slug,
        parcelFriendly: true,
        baseServings: 2,
        difficulty: 'Easy',
        handsOn: '10 min',
        leadDays: 1,
        butcherTip: seed.parcelTip,
        buy: [primaryBuy.item],
        sides: [],
        upgrades: [],
        perfectFor: 'Two-serving parchment dinner',
        occasions: ['weeknight', 'date-night'],
        cut: seed.cut,
        title: seed.sheetTitle,
        intro: seed.parcelTip,
        serves: '2',
        prep: '5 min',
        cook: seed.bakeTime,
        total: seed.bakeTime,
        ingredients: [seed.bedLabel, seed.zone3Label, seed.zone4Label, seed.zone5Label],
        tools: ['Half-sheet pan', '12×16 parchment liner'],
        steps: [],
    };

    const zones: ResolvedSheetZone[] = [
        {
            step: 1,
            cxIn: 5.75,
            cyIn: bedBox.cyIn,
            widthIn: bedBox.widthIn,
            heightIn: bedBox.heightIn,
            shape: seed.bedShape,
            label: seed.bedLabel,
            scaleNote: seed.bedScaleNote,
            instruction: seed.bedInstruction,
            parts: seed.bedParts,
            isPrimaryCut: false,
        },
        {
            step: 2,
            cxIn: 5.75,
            cyIn: primaryBox.cyIn,
            widthIn: primaryBox.widthIn,
            heightIn: primaryBox.heightIn,
            shape: seed.primaryShape,
            label: seed.primaryLabel,
            scaleNote: seed.primaryScaleNote,
            instruction: seed.primaryInstruction,
            parts: seed.primaryParts,
            isPrimaryCut: true,
        },
        {
            step: 3,
            cxIn: 2.55,
            cyIn: 9.35,
            widthIn: 1.9,
            heightIn: 1.1,
            shape: 'seasoning-pair',
            label: seed.zone3Label,
            scaleNote: 'Ø 0.85 + Ø 0.65 in pinches',
            instruction: 'Season cuts evenly on both sides',
            parts: seed.zone3Parts,
            isPrimaryCut: false,
        },
        {
            step: 4,
            cxIn: 5.65,
            cyIn: 9.35,
            widthIn: seed.zone4Shape === 'mustard-honey-garlic' ? 3.5 : 2.9,
            heightIn: seed.zone4Shape === 'butter-lemon' ? 2.15 : 1.35,
            shape: seed.zone4Shape,
            label: seed.zone4Label,
            scaleNote: seed.zone4ScaleNote,
            instruction: seed.zone4Instruction,
            parts: seed.zone4Parts,
            isPrimaryCut: false,
        },
        {
            step: 5,
            cxIn: 8.7,
            cyIn: 9.22,
            widthIn: 2.35,
            heightIn: 2.1,
            shape: seed.zone5Shape,
            label: seed.zone5Label,
            scaleNote: seed.zone5ScaleNote,
            instruction: seed.zone5Instruction,
            parts: seed.zone5Parts,
            isPrimaryCut: false,
        },
    ];

    return {
        slug: seed.slug,
        recipe: syntheticRecipe,
        sheetTitle: seed.sheetTitle,
        servings: EXTENDED_SERVINGS,
        ovenTemp: seed.ovenTemp,
        bakeTime: seed.bakeTime,
        pullTemp: seed.pullTemp,
        parcelTip: seed.parcelTip,
        vignetteImage: seed.vignetteImage,
        foldSteps: [
            'Bring left & right long edges together above the food and double-crease 1/2 in twice.',
            'Tuck top corners inward along angled dashes and roll the top flap snug.',
            'Add Zone 05 splash if listed, crimp bottom corners hard underneath, and bake on a sheet pan.',
        ],
        buyPlans: [primaryBuy],
        primaryBuy,
        estimatedTotal: seed.estimatedTotal,
        onlineOrderPath,
        onlineOrderQrUrl,
        scaledIngredients: syntheticRecipe.ingredients,
        zones,
    };
}

